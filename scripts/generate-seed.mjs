const categoryRows = [];
const versionRows = [];
const attrRows = [];
const reqRows = [];
const areaLinkRows = [];

for (const file of files) {
  const config = JSON.parse(readFileSync(join(seedsDir, file), 'utf8'));
  const slug = config.slug;
  const catId = catIds[slug];
  const verId = verIds[slug];
  if (!catId || !verId) {
    throw new Error(`Missing fixed UUID for slug ${slug}`);
  }

  const published = config.status === 'pilot' || config.status === 'live';
  categoryRows.push(
    `  (${sqlString(catId)}, ${sqlString(slug)}, ${sqlString(config.name)}, ${sqlString(config.icon)}, ${sqlString(config.status)}, null)`,
  );
  versionRows.push(
    `  (${sqlString(verId)}, ${sqlString(catId)}, 1, 'Seed import', ${sqlString(config.status)}, ${published}, ${published ? "timezone('utc', now())" : 'null'}, ${sqlJson(config)}, 'seed')`,
  );

  config.attributes.forEach((attr, i) => {
    const options = attr.options ? sqlJson(attr.options) : 'null';
    const validation = attr.validation ? sqlJson(attr.validation) : 'null';
    const unit = attr.unit ? sqlString(attr.unit) : 'null';
    attrRows.push(
      `  (${sqlString(verId)}, ${sqlString(attr.key)}, ${sqlString(attr.label)}, ${sqlString(attr.type)}, ${attr.required}, ${sqlString(attr.applies_to)}, ${options}, ${unit}, ${validation}, ${i})`,
    );
  });

  config.vendor_requirements.forEach((req, i) => {
    reqRows.push(`  (${sqlString(verId)}, ${sqlString(req)}, ${i})`);
  });

  for (const areaId of leafAreaIds) {
    areaLinkRows.push(`  (${sqlString(catId)}, ${sqlString(areaId)})`);
  }
}

const body = [
  'insert into public.categories (id, slug, name, icon, status, current_version_id) values',
  categoryRows.join(',\n') + ';',
  '',
  'insert into public.category_versions (id, category_id, version_number, note, status, published, published_at, config, created_by) values',
  versionRows.join(',\n') + ';',
  '',
  'update public.categories c',
  'set current_version_id = v.id',
  'from public.category_versions v',
  'where v.category_id = c.id and v.version_number = 1;',
  '',
  'insert into public.category_attributes (category_version_id, key, label, type, required, applies_to, options, unit, validation, sort_order) values',
  attrRows.join(',\n') + ';',
  '',
  'insert into public.vendor_requirements (category_version_id, requirement, sort_order) values',
  reqRows.join(',\n') + ';',
  '',
  'insert into public.category_areas (category_id, area_id) values',
  areaLinkRows.join(',\n') + ';',
  '',
].join('\n');

writeFileSync(join(root, 'supabase/seed.sql'), header + body);
console.log(`Wrote supabase/seed.sql with ${files.length} categories`);
